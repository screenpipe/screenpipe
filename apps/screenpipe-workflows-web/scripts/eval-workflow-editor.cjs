// screenpipe — AI that knows everything you've seen, said, or heard
// https://screenpipe.com
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const out = process.env.WORKFLOW_EDITOR_ARTIFACTS || require("node:path").join(require("node:os").tmpdir(), "screenpipe-workflow-editor-eval");
require("node:fs").mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, channel: "chrome" });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  let initialBlocks;
  page.on("pageerror", e => errors.push(e.message));
  const field = name => page.getByRole("textbox", { name, exact: true });
  const button = name => page.getByRole("button", { name, exact: true });
  const saved = () => page.getByRole("status", { name: "Save status" }).filter({ hasText: /^Saved$/ }).waitFor();
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem("screenpipe:fictional-workflow-editor-preview"))?.analysis.workflows.find(w => w.id === "Research synthesis"));
  const check = async (label, f) => { await f(); console.log("PASS", label); };
  try {
    await page.goto(process.env.WORKFLOWS_PREVIEW_URL || "http://127.0.0.1:1431/preview");
    await button("Open map").first().click();
    await check("workflow is editable immediately, without edit/save controls", async () => {
      await field("Workflow title").waitFor();
      assert.equal(await button("Edit workflow").count(), 0);
      assert.equal(await button("Edit steps").count(), 0);
      assert.equal(await button("Save").count(), 0);
      assert.equal(await button("Move step 1").getAttribute("draggable"), "true");
    });
    await check("open questions launch focused feedback and preserve unanswered questions", async () => {
      const question = "Who reviews the synthesis before it is shared?";
      const questions = page.getByRole("region", { name: "Open questions", exact: true });
      await questions.getByRole("button", { name: question, exact: true }).focus();
      await page.keyboard.press("Enter");
      const chat = page.getByRole("region", { name: "Screenpipe assistant", exact: true });
      await chat.getByRole("log").getByText(question, { exact: true }).waitFor();
      assert.equal(await chat.getByRole("button", { name: "Stop answer" }).count(), 0);
      assert.equal(await chat.getByRole("button", { name: "Save feedback" }).count(), 0);
      await chat.getByRole("textbox", { name: "Ask Screenpipe", exact: true }).fill("Keep this unfinished answer");
      await chat.getByRole("button", { name: "Minimize chat", exact: true }).click();
      await questions.getByRole("button", { name: question, exact: true }).click();
      assert.equal(await chat.getByRole("textbox", { name: "Ask Screenpipe", exact: true }).inputValue(), "Keep this unfinished answer");
      assert.equal(await chat.getByRole("log").getByText(question, { exact: true }).count(), 1);
      await page.screenshot({ path: out + "/question-chat.png" });
      await chat.getByRole("textbox", { name: "Ask Screenpipe", exact: true }).fill("The research lead reviews it before sharing.");
      await chat.getByRole("button", { name: "Send feedback", exact: true }).click();
      await chat.getByRole("button", { name: "Save feedback", exact: true }).click();
      await chat.getByText("Feedback saved for the next update", { exact: true }).waitFor();
      await chat.getByRole("button", { name: "Minimize chat", exact: true }).click();
      assert(await questions.getByRole("button", { name: question, exact: true }).isVisible());
      const references = page.getByRole("region", { name: "References for Collect sources", exact: true });
      await references.getByText("Unresolved details", { exact: true }).click();
      await references.getByRole("button", { name: "Where should the source list be saved?", exact: true }).click();
      await chat.getByRole("log").getByText("Where should the source list be saved?", { exact: true }).waitFor();
      await chat.getByText("Collect sources", { exact: true }).waitFor();
      await chat.getByRole("button", { name: "Minimize chat", exact: true }).click();
      await references.getByText("Unresolved details", { exact: true }).click();
      await field("Workflow title").focus();
    });
    await check("details stay visible while editing controls disclose on hover and focus", async () => {
      initialBlocks = await page.getByRole("article", { name: "Step 1", exact: true }).getByRole("textbox").evaluateAll(es => es.filter(e => e.getAttribute("aria-label").startsWith("Block ")).map(e => e.value));
      assert.equal(initialBlocks.length, 3);
      assert(initialBlocks.every(Boolean));
      assert.equal(await page.getByText("Drag handles to reorder", { exact: false }).count(), 0);
      await page.mouse.move(0, 0);
      await page.waitForTimeout(150);
      assert.equal(await button("Move step 1").evaluate(e => getComputedStyle(e).opacity), "0");
      assert.equal(await button("Move block 1 in step 1").evaluate(e => getComputedStyle(e).opacity), "0");
      await field("Step 1 title").hover();
      await page.waitForTimeout(150);
      assert.equal(await button("Move step 1").evaluate(e => getComputedStyle(e).opacity), "1");
      assert.equal(await button("Move step 2").evaluate(e => getComputedStyle(e).opacity), "0");
      await page.mouse.move(0, 0);
      await button("Move step 2").focus();
      await page.waitForTimeout(150);
      assert.equal(await button("Move step 2").evaluate(e => getComputedStyle(e).opacity), "1");
      await field("Workflow title").focus();
      const references = page.getByRole("region", { name: "References for Collect sources", exact: true });
      await references.getByText("1 source", { exact: true }).click();
      const raw = references.getByRole("region", { name: "Captured text 1 for Collect sources", exact: true });
      assert.equal(await raw.isVisible(), false);
      await references.getByText("Captured text", { exact: true }).click();
      await raw.waitFor();
      await references.getByText("1 source", { exact: true }).click();
      const enlarge = references.getByRole("button", { name: "Enlarge screenshot for Collect sources" });
      const smallWidth = (await enlarge.boundingBox()).width;
      await enlarge.click();
      const reduce = references.getByRole("button", { name: "Reduce screenshot for Collect sources" });
      assert((await reduce.boundingBox()).width > smallWidth);
      await page.screenshot({ path: out + "/screenshot-expanded.png" });
      await reduce.click();
      await references.getByRole("button", { name: "View recording for Collect sources" }).click();
      await references.getByRole("img", { name: "Captured moment for Collect sources", exact: true }).waitFor();
      await references.getByRole("button", { name: "Close recording for Collect sources" }).click();
    });
    await check("step controls stay reachable and dismiss with Escape or an outside click", async () => {
      await field("Step 1 title").hover();
      const grip = button("Move step 1");
      const bounds = await grip.boundingBox();
      await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2, { steps: 12 });
      assert.equal(await grip.evaluate(e => getComputedStyle(e).opacity), "1");
      const actions = page.getByLabel("Step 1 actions", { exact: true });
      await actions.click();
      await button("Move step 1 down").focus();
      await page.keyboard.press("Escape");
      assert.equal(await button("Move step 1 down").isVisible(), false);
      assert.equal(await actions.evaluate(e => e === document.activeElement), true);
      await actions.click();
      await field("Workflow title").click();
      assert.equal(await button("Move step 1 down").isVisible(), false);
    });
    await check("block handle reveals stable click-open actions without hover layout shifts", async () => {
      const text = field("Block 1 in step 1");
      const grip = button("Move block 1 in step 1");
      const before = await text.boundingBox();
      assert.equal(await page.getByRole("combobox", { name: "Block 1 type in step 1" }).count(), 0);
      assert.equal(await button("Delete block 1 in step 1").count(), 0);
      await text.hover();
      const handle = await grip.boundingBox();
      await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2, { steps: 12 });
      assert.equal(await grip.evaluate(e => getComputedStyle(e).opacity), "1");
      assert.deepEqual(await text.boundingBox(), before);
      await grip.click();
      const menu = page.getByRole("dialog", { name: "Actions for block 1 in step 1" });
      await menu.waitFor();
      await page.mouse.move(0, 0);
      assert.equal(await menu.isVisible(), true);
      await page.getByRole("combobox", { name: "Block 1 type in step 1" }).selectOption("decision");
      await saved();
      assert.equal((await stored()).stages[0].procedure[0].kind, "decision");
      await page.screenshot({ path: out + "/block-actions.png" });
      await page.keyboard.press("Escape");
      assert.equal(await menu.count(), 0);
      assert(await grip.evaluate(e => document.activeElement === e));
      await grip.click();
      await field("Workflow title").click();
      assert.equal(await menu.count(), 0);
      await button("Undo last edit").click(); await saved();
      await grip.focus(); await page.keyboard.press("Enter");
      await button("Delete block 1 in step 1").click(); await saved();
      assert.equal((await stored()).stages[0].procedure.length, initialBlocks.length - 1);
      await button("Undo last edit").click(); await saved();
      assert.deepEqual((await stored()).stages[0].procedure.map(p => p.text), initialBlocks);
    });
    await check("drag step, auto-save and retain its screenshot", async () => {
      await page.getByRole("article", { name: "Step 1", exact: true }).hover();
      await button("Move step 1").dragTo(field("Step 2 title"));
      assert.equal(await field("Step 2 title").inputValue(), "Collect sources");
      await saved();
      const workflow = await stored();
      assert.equal(workflow.stages[1].name, "Collect sources");
      assert(workflow.stages[1].screenshot.dataUrl);
    });
    await check("undo works after automatic save", async () => {
      await button("Undo last edit").click();
      assert.equal(await field("Step 1 title").inputValue(), "Collect sources");
      await saved();
      assert.equal((await stored()).stages[0].name, "Collect sources");
    });
    await check("successive saved reorders preserve source identity", async () => {
      const before = await stored();
      await button("Move step 1").focus();
      await page.keyboard.press("Alt+ArrowDown");
      await saved();
      await button("Move step 2").focus();
      await page.keyboard.press("Alt+ArrowDown");
      await saved();
      const after = await stored();
      assert.equal(after.stages[2].name, "Collect sources");
      assert.deepEqual(after.stages[2].screenshot, before.stages[0].screenshot);
      await button("Move step 3").focus();
      await page.keyboard.press("Alt+ArrowUp");
      await saved();
      await button("Move step 2").focus();
      await page.keyboard.press("Alt+ArrowUp");
      await saved();
      assert.equal((await stored()).stages[0].name, "Collect sources");
    });
    await check("typing auto-saves without losing focus", async () => {
      await field("Workflow title").fill("Research brief");
      await saved();
      assert(await field("Workflow title").evaluate(e => e === document.activeElement));
      assert.equal((await stored()).title, "Research brief");
    });
    await check("empty blocks remain drafts until filled", async () => {
      const before = await stored();
      await field("Step 1 title").hover();
      await button("Add block").first().click();
      await page.getByText("Finish the empty block to save", { exact: true }).waitFor();
      await page.waitForTimeout(850);
      assert.equal((await stored()).revision, before.revision);
      await field("Block 4 in step 1").fill("Gather the dated source links.");
      await saved();
      await field("Step 1 title").hover();
      await button("Add block").first().click();
      await field("Block 5 in step 1").fill("Check the source author.");
      await saved();
    });
    await check("drag blocks auto-saves their new order", async () => {
      await field("Block 4 in step 1").hover();
      await button("Move block 4 in step 1").dragTo(field("Block 5 in step 1"));
      await saved();
      assert.deepEqual((await stored()).stages[0].procedure.map(p => p.text), [...initialBlocks, "Check the source author.", "Gather the dated source links."]);
    });
    await check("failed auto-save keeps text, exposes retry, does not loop", async () => {
      await page.evaluate(() => {
        window.__setItem = Storage.prototype.setItem;
        window.__failedSaves = 0;
        Storage.prototype.setItem = function(k, v) {
          if (k === "screenpipe:fictional-workflow-editor-preview") { window.__failedSaves++; throw new Error("Simulated disk full"); }
          return window.__setItem.call(this, k, v);
        };
      });
      await field("Workflow description").fill("A traceable research brief for the team.");
      await page.getByRole("alert").filter({ hasText: "Simulated disk full" }).waitFor();
      await page.waitForTimeout(850);
      assert.equal(await page.evaluate(() => window.__failedSaves), 1);
      assert.equal(await field("Workflow description").inputValue(), "A traceable research brief for the team.");
      await page.evaluate(() => Storage.prototype.setItem = window.__setItem);
      await button("Retry save").click();
      await saved();
    });
    await check("leaving before debounce flushes valid changes", async () => {
      await field("Workflow outcome").fill("A reviewed brief is ready to share.");
      await button("All workflows").click();
      await page.waitForFunction(() => JSON.parse(localStorage.getItem("screenpipe:fictional-workflow-editor-preview")).analysis.workflows.some(w => w.outcome === "A reviewed brief is ready to share."));
      await button("Open map").first().click();
      assert.equal(await field("Workflow outcome").inputValue(), "A reviewed brief is ready to share.");
    });
    await check("reload restores saved title, steps and blocks", async () => {
      await page.reload();
      await button("Open map").first().click();
      assert.equal(await field("Workflow title").inputValue(), "Research brief");
      assert.equal(await field("Step 1 title").inputValue(), "Collect sources");
      assert.equal(await field("Block 4 in step 1").inputValue(), "Check the source author.");
      assert.equal(await field("Block 1 in step 1").inputValue(), initialBlocks[0]);
    });
    await check("concurrent change rejected with local draft retained", async () => {
      await page.evaluate(() => {
        const k = "screenpipe:fictional-workflow-editor-preview";
        const v = JSON.parse(localStorage.getItem(k));
        const workflow = v.analysis.workflows.find(w => w.id === "Research synthesis");
        workflow.revision++;
        workflow.title = "Another editor's title";
        localStorage.setItem(k, JSON.stringify(v));
      });
      await field("Workflow title").fill("My local draft");
      await page.getByRole("alert").filter({ hasText: "Workflow changed" }).waitFor();
      assert.equal(await field("Workflow title").inputValue(), "My local draft");
      assert.equal((await stored()).title, "Another editor's title");
      await button("Discard draft and view latest").click();
      assert.equal(await field("Workflow title").inputValue(), "Another editor's title");
    });
    await check("incomplete draft survives navigation", async () => {
      await button("Add step").click();
      await button("All workflows").click();
      await button("Open map").first().click();
      assert.equal(await field("Step 4 title").inputValue(), "");
      await field("Step 4 title").fill("Send for review");
      await saved();
    });
    await page.locator("[data-workflows-scroll-region]").evaluate(e => e.scrollTop = 0);
    await page.screenshot({ path: out + "/inline-workflow.png" });
    for (const width of [1050, 720, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      if (width < 680) await button("Collapse left sidebar").click();
      await check(`fields and controls fit at ${width}px`, async () => {
        await page.waitForTimeout(100);
        const bad = await page.locator("main textarea, main button").evaluateAll(es => es.filter(e => e.getBoundingClientRect().width && (e.getBoundingClientRect().right > innerWidth + 1 || (e.tagName === "TEXTAREA" && e.scrollHeight > e.clientHeight + 3))).map(e => e.getAttribute("aria-label") || e.textContent));
        assert.deepEqual(bad, []);
      });
      await button("Move block 1 in step 1").focus();
      await page.keyboard.press("Enter");
      const menu = page.getByRole("dialog", { name: "Actions for block 1 in step 1" });
      assert(await menu.evaluate(e => { const r = e.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; }));
      await page.keyboard.press("Escape");
      await page.screenshot({ path: `${out}/inline-${width}.png` });
    }
    await check("legacy evidence is retained without procedure blocks or screenshots", async () => {
      const catalog = await page.evaluate(() => JSON.parse(localStorage.getItem("screenpipe:fictional-workflow-editor-preview")));
      catalog.analysis.workflows = catalog.analysis.workflows.filter(w => w.id === "Research synthesis");
      const stage = catalog.analysis.workflows[0].stages[0];
      stage.procedure = [];
      stage.screenshot = null;
      stage.evidence[0].detail = "Fictional capture: navigation toolbar sidebar unread messages. ".repeat(700);
      const context = await browser.newContext();
      await context.addInitScript(data => localStorage.setItem("screenpipe:fictional-workflow-editor-preview", JSON.stringify(data)), catalog);
      context.setDefaultTimeout(10000);
      const legacy = await context.newPage();
      await legacy.goto(process.env.WORKFLOWS_PREVIEW_URL || "http://127.0.0.1:1431/preview");
      await legacy.getByRole("button", { name: "Open map", exact: true }).first().click();
      const references = legacy.getByRole("region", { name: `References for ${stage.name}`, exact: true });
      await references.getByText("1 source", { exact: true }).click();
      const raw = references.getByRole("region", { name: `Captured text 1 for ${stage.name}`, exact: true });
      assert.equal(await raw.isVisible(), false);
      await references.getByText("Captured text", { exact: true }).click();
      assert.equal(await raw.textContent(), stage.evidence[0].detail);
      assert((await raw.boundingBox()).height <= 185);
      assert(await raw.evaluate(e => e.scrollHeight > e.clientHeight));
      await legacy.screenshot({ path: out + "/long-source.png" });
      await legacy.setViewportSize({ width: 390, height: 900 });
      await legacy.getByRole("button", { name: "Collapse left sidebar", exact: true }).click();
      assert(await raw.evaluate(e => e.getBoundingClientRect().right <= innerWidth));
      await context.close();
    });
    await check("touch layout keeps controls hidden until a step is focused", async () => {
      const context = await browser.newContext({ viewport: { width: 390, height: 900 }, isMobile: true, hasTouch: true });
      context.setDefaultTimeout(10000);
      const touch = await context.newPage();
      await touch.goto(process.env.WORKFLOWS_PREVIEW_URL || "http://127.0.0.1:1431/preview");
      await touch.getByRole("button", { name: "Open map", exact: true }).first().tap();
      const grip = touch.getByRole("button", { name: "Move step 1", exact: true });
      assert.equal(await grip.evaluate(e => getComputedStyle(e).opacity), "0");
      await touch.getByRole("textbox", { name: "Step 1 title", exact: true }).tap();
      await touch.waitForTimeout(150);
      assert.equal(await grip.evaluate(e => getComputedStyle(e).opacity), "1");
      await context.close();
    });
    assert.deepEqual(errors, []);
    console.log("PASS no browser exceptions");
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
